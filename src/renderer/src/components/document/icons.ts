// `Map` 图标组件在上面的 import 里，这里显式用全局构造器避免被遮蔽。
const cache = new globalThis.Map<string, string>();

function brandSvg(path: string): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24" fill="currentColor" aria-hidden="true" focusable="false"><path d="${path}"/></svg>`;
}

function genericSvg(Icon: LucideIcon): string {
  return renderToStaticMarkup(
    createElement(Icon, { size: 24, strokeWidth: 2, "aria-hidden": true, focusable: "false" }),
  );
}

/** `icon:name` → 内联 SVG 字符串；未登记的名字返回 null（调用方保留原文）。 */
export function iconSvg(name: string): string | null {
  const key = name.trim().toLowerCase();
  const cached = cache.get(key);
  if (cached !== undefined) return cached;

  const brandPath = BRAND_PATHS[BRAND_ALIASES[key] ?? key];
  let svg: string | null = null;
  if (brandPath !== undefined) {
    svg = brandSvg(brandPath);
  } else {
    const Icon = GENERIC_COMPONENTS[GENERIC_ALIASES[key] ?? key];
    if (Icon !== undefined) {
      try {
        svg = genericSvg(Icon);
      } catch {
        // 单个图标渲染失败不该毁掉整份文档。
        svg = null;
      }
    }
  }

  if (svg !== null) cache.set(key, svg);
  return svg;
}
